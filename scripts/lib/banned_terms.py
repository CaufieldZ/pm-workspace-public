# § 4 翻译腔检测（英文直译 · 中文母语者不会这么写）
# ═══════════════════════════════════════════════════════════════

# 思路：英文语法正常的多词结构，直译过来就冗余 / 肿胀 / 不像人话。
# 三类：① 语义冗余（英文正常，中文重复）② 介词链膨胀（中文用逗号/动词替代）
# ③ 英文句式直译（中文母语者不用的句子结构）。
# 全 warn 级，不阻断——先跑数据看假阳率，后续挑高精度项升 strict。

# ─ 4.1 语义冗余 ─
# 英文多词结构直译后语义重复：中文一个词就能说完的用了两个。

SEMANTIC_REDUNDANCY_PATTERNS = [
    # based on the basis of → 基于...的基础（之上）
    # 例：基于用户反馈的基础之上 → 基于用户反馈
    (re.compile(r"基于.{1,12}的基础之上"),
     "翻译腔：「基于…的基础之上」→ 删「的基础之上」（例：「基于用户反馈的基础之上优化」→「基于用户反馈优化」）"),
    # for the purpose of → 为了...的目的
    # 例：为了提升转化率的目的 → 为了提升转化率
    (re.compile(r"为了.{1,12}的目的"),
     "翻译腔：「为了…的目的」→ 删「的目的」（例：「为了提升转化率的目的」→「为了提升转化率」）"),
    # allows ... to be able to → 允许...能够
    # 例：允许用户能够创建 → 用户可以创建
    (re.compile(r"允许.{1,15}能够"),
     "翻译腔：「允许…能够」→ 直接主语动宾（例：「允许用户能够创建直播间」→「用户可以创建直播间」）"),
    # enables / makes it so that ... can → 使得...能够（中间 > 4 字才报，短距合法）
    # 例：使得整个推送流程能够自动化 → 让推送流程自动化
    (re.compile(r"使得.{5,20}能够"),
     "翻译腔：「使得…能够」→ 换「让」或主谓直写（例：「使得整个推送流程能够自动化」→「让推送流程自动化」）"),
]

# ─ 4.2 介词膨胀 ─
# 英文靠介词链串长句，中文用逗号 / 动词 / 话题化替代。
# 短距豁免（如「在正常情况下的」是正常中文），只查≥5 字的肿胀中间段。

PREPOSITION_INFLATION_PATTERNS = [
    # by means of / through → 通过...的方式（直接动宾更好）
    # 例：通过手动输入的方式创建 → 手动输入创建
    (re.compile(r"通过.{3,30}的方式"),
     "翻译腔：「通过…的方式」→ 去掉包装，直接动宾（例：「通过手动输入的方式创建」→「手动输入创建」）"),
    # in the process of → 在...的过程中（...时 就够了）
    # 例：在创建订单的过程中 → 创建订单时
    (re.compile(r"在.{5,30}的过程中"),
     "翻译腔：「在…的过程中」→ 换「…时」（例：「在创建订单的过程中」→「创建订单时」）"),
    # in the case of → 在...的情况下（≤5 字如「在正常情况下」豁免）
    # 例：在用户多次登录失败的情况下 → 用户多次登录失败后
    (re.compile(r"在.{5,30}的情况下"),
     "翻译腔：「在…的情况下」→ 换「…后/时/若」（例：「在用户多次登录失败的情况下」→「用户多次登录失败后」）"),
    # from the perspective of → 从...的角度（来看|出发）（≤4 字如「从用户角度」豁免）
    # 例：从运营策略和数据增长的角度来看 → 对运营策略和数据增长来说
    (re.compile(r"从.{5,30}的角度(?:来看|出发|看)"),
     "翻译腔：「从…的角度来看」→ 直接说立场（例：「从运营策略的角度来看」→「对运营策略来说」）"),
]

# ─ 4.3 英文句式直译 ─
# 英文常用句型，直译后中文母语者自然写作时不会选用。

ENGLISH_CALQUE_PATTERNS = [
    # there exists → 存在着（中文用「有」或直接给主语）
    # 例：系统中存在着大量冗余数据 → 系统中有大量冗余数据
    (re.compile(r"存在着"),
     "翻译腔：「存在着」→ 换「有」（例：「系统中存在着大量冗余数据」→「系统中有大量冗余数据」）"),
    # is used for / is ...ed → 被用于（不必要的被动，中文「用于」即可）
    # 例：该接口被用于获取用户信息 → 该接口用于获取用户信息
    (re.compile(r"被用于"),
     "翻译腔：「被用于」→ 去「被」（例：「该接口被用于获取用户信息」→「该接口用于获取用户信息」）"),
    # this means that → 这意味着（英文语序，中文说「也就是」或直接重写）
    # 例：这意味着我们需要重新设计 → 也就是要重新设计
    (re.compile(r"这意味着"),
     "翻译腔：「这意味着」→ 换「也就是」或合并主句（例：「这意味着需要重新设计」→「也就是要重新设计」）"),
    # plays the role of → 扮演...角色（除非真在讲戏剧/游戏角色）
    # 例：内容在社区中扮演了核心驱动力的角色 → 内容是社区的核心驱动力
    (re.compile(r"扮演.{1,20}角色"),
     "翻译腔：「扮演…角色」→ 直接「是」（例：「内容扮演了核心驱动力的角色」→「内容是核心驱动力」）"),
    # it is important to note that → 值得注意的是 / 需要指出的是
    # 例：值得注意的是用户留存率下降了 → 用户留存率下降了（直接给数据）
    (re.compile(r"(?:值得注意的是|需要指出的是|值得一提的是|需要注意的是)"),
     "翻译腔：「值得注意的是…」→ 删评注插入语，直接给数据（例：「值得注意的是留存下降」→「留存下降」）"),
    # in terms of / regarding → 就...而言（文言残留 + 英文语序）
    # 例：就内容质量而言 → 内容质量上 / 直接说
    (re.compile(r"就.{3,20}而言"),
     "翻译腔：「就…而言」→ 换「在…上」或直接陈述（例：「就内容质量而言」→「内容质量上」）"),
    # due to the fact that / because of → 由于...的原因（语义重复）
    # 例：由于网络延迟的原因 → 因为网络延迟
    (re.compile(r"由于.{1,15}的原因"),
     "翻译腔：「由于…的原因」→ 删「的原因」（例：「由于网络延迟的原因」→「由于网络延迟」）"),
    # the majority of / a lot of → 大量的 / 大多数的（英文量化习惯，中文常可删）
    # 这类太常见，只报 ≥ 2 次出现在同行才提示——不在此做，后面看统计数据加。
]

# 全部翻译腔模式（warn 级用）
TRANSLATION_ESE_PATTERNS = (
    SEMANTIC_REDUNDANCY_PATTERNS
    + PREPOSITION_INFLATION_PATTERNS
    + ENGLISH_CALQUE_PATTERNS
)

